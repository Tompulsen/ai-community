import { expect, test } from '@playwright/test'
import { mockUnifiedAccount } from './helpers/account-fixture'

test('avatar hover previews the account while clicking opens the personal homepage', async ({ page }) => {
  const fixture = await mockUnifiedAccount(page, true)
  await page.goto('/discover')
  const avatar = page.locator('.profile-toggle'), card = page.locator('.account-popover')
  await expect(avatar).toHaveAttribute('href', `/community?creator=${fixture.state.user.id}`)
  expect((await page.locator('.profile-menu').boundingBox())!.width).toBeCloseTo(44, 0)
  await expect(page.locator('.profile-menu-toggle')).toHaveCount(0)
  await avatar.hover()
  await expect(card).toContainText(fixture.state.user.name)
  await expect(card).toContainText('章鱼号：17')
  await expect(page).toHaveURL('/discover')
  const destination = card.getByRole('link', { name: '个人主页', exact: true })
  const bounds = (await destination.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2, { steps: 12 })
  await expect(destination).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('avatar-hover.png') })
  await page.mouse.move(100, 500)
  await expect(card).not.toBeVisible()
  await avatar.click()
  await expect(page).toHaveURL(`/community?creator=${fixture.state.user.id}`)
  await expect(card).not.toBeVisible()
})

test('keyboard users can enter the account card, dismiss it and navigate directly', async ({ page }) => {
  const fixture = await mockUnifiedAccount(page, true)
  await page.goto('/discover')
  const avatar = page.locator('.profile-toggle'), card = page.locator('.account-popover')
  await avatar.focus()
  await expect(card).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(card.getByRole('link', { name: '个人主页', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(card).not.toBeVisible()
  await expect(avatar).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(card).not.toBeVisible()
  await avatar.focus()
  await expect(card).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(`/community?creator=${fixture.state.user.id}`)
})

test('account hover shares menu dismissal and closes when the signed-in account changes', async ({ page }) => {
  const fixture = await mockUnifiedAccount(page, true)
  fixture.state.user.isAdmin = true
  await page.goto('/discover')
  const card = page.locator('.account-popover')
  await page.locator('.profile-toggle').hover()
  await expect(card.getByRole('link', { name: '内容管理', exact: true })).toBeVisible()
  await page.locator('.message-trigger').hover()
  await expect(page.locator('.message-popover')).toBeVisible()
  await expect(card).not.toBeVisible()
  await page.locator('.profile-toggle').hover()
  await expect(card).toBeVisible()
  await expect(page.locator('.message-popover')).not.toBeVisible()
  fixture.state.user = { ...fixture.state.user, id: 'anotherAccount', name: '另一位创作者', isAdmin: false }
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(card).not.toBeVisible()
  await page.locator('.profile-toggle').hover()
  await expect(card).toContainText('另一位创作者')
  await expect(card.getByRole('link', { name: '内容管理', exact: true })).toHaveCount(0)
})

test.describe('touch on a desktop layout', () => {
  test.use({ viewport: { width: 1280, height: 900 }, hasTouch: true })
  test('keyboard focus keeps Studio actions reachable while tapping the avatar navigates directly', async ({ page }) => {
    const fixture = await mockUnifiedAccount(page, true)
    await page.goto('/create/text')
    await page.locator('.message-trigger').tap()
    await expect(page.locator('.message-popover')).toBeVisible()
    await page.locator('.profile-toggle').focus()
    const card = page.locator('.account-popover')
    await expect(card.getByRole('link', { name: '账号设置', exact: true })).toBeVisible()
    await expect(card.getByRole('button', { name: '退出登录', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(card).not.toBeVisible()
    await page.locator('.profile-toggle').tap()
    await expect(page).toHaveURL(`/community?creator=${fixture.state.user.id}`)
    await expect(card).not.toBeVisible()
  })
})
