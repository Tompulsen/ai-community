test('canvas pans, zooms around the pointer and accepts dropped references without changing source pixels', async ({ page }) => {
  const { image, donor, calls } = await fixture(page)
  await upload(page, image)
  const editor = await openCanvas(page), stage = editor.locator('.canvas-stage'), source = editor.locator('[data-canvas-node="source"]')
  const b = (await stage.boundingBox())!, before = (await source.boundingBox())!
  await page.mouse.move(b.x + b.width - 12, b.y + 65)
  await page.mouse.down(); await page.mouse.move(b.x + b.width - 82, b.y + 95, { steps: 4 }); await page.mouse.up()
  const panned = (await source.boundingBox())!
  expect(panned.x).toBeCloseTo(before.x - 70, 0)
  expect(panned.y).toBeCloseTo(before.y + 30, 0)
  const anchor = { x: panned.x + panned.width * .4, y: panned.y + panned.height * .6 }
  await page.mouse.move(anchor.x, anchor.y); await page.mouse.wheel(0, -180)
  await expect.poll(async () => (await source.boundingBox())!.width).toBeGreaterThan(panned.width)
  const zoomed = (await source.boundingBox())!
  expect((anchor.x - zoomed.x) / zoomed.width).toBeCloseTo(.4, 2)
  expect((anchor.y - zoomed.y) / zoomed.height).toBeCloseTo(.6, 2)
  await stage.evaluate((el, { base64, x, y }) => {
    const transfer = new DataTransfer()
    transfer.items.add(new File([Uint8Array.from(atob(base64), c => c.charCodeAt(0))], 'drop.png', { type: 'image/png' }))
    el.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, clientX: x, clientY: y, dataTransfer: transfer }))
  }, { base64: donor.toString('base64'), x: b.x + b.width / 2, y: b.y + b.height / 2 })
  await expect(editor.locator('[data-canvas-node]')).toHaveCount(2)
  await editor.getByRole('button', { name: '向右移动图片', exact: true }).click()
  await editor.getByRole('button', { name: '删除选中参考图', exact: true }).click()
  await expect(editor.locator('[data-canvas-node]')).toHaveCount(1)
  await editor.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(editor.locator('[data-canvas-node]')).toHaveCount(2)
  expect(calls).toHaveLength(0)
})

