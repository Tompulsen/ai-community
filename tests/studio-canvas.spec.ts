async function fixture(page: Page, kind: 'image' | 'text' | 'video' = 'image', maxReferenceImages = 16) {
  const account = await mockUnifiedAccount(page, true)
  account.state.user.id = '17'
  const image = await sharp({ create: { width: 1200, height: 800, channels: 3, background: '#e0e9e9' } }).png().toBuffer()
  const donor = await sharp({ create: { width: 480, height: 360, channels: 3, background: '#336699' } }).png().toBuffer()
  const preview = await sharp(image).resize(360).webp().toBuffer()
  const calls: any[] = []
  await page.route('**/api/creation/**', route => {
    const url = new URL(route.request().url()), path = url.pathname
    if (path === '/api/creation/models') return route.fulfill({ json: { tokenId: 41, items: [
      { id: 'gpt-image-2', kinds: ['image'], image: { maxReferenceImages } },
      { id: 'gpt-5', kinds: ['text'] }, { id: 'sora-2', kinds: ['video'] },
    ] } })
    if (path === '/api/creation/media') return route.fulfill({ contentType: url.searchParams.has('variant') ? 'image/webp' : 'image/png', body: url.searchParams.has('variant') ? preview : image })
    if (path === '/api/creation/skills/catalog') return route.fulfill({ json: { items: [] } })
    if (path === '/api/creation/mcp/status') return route.fulfill({ json: { enabled: false, items: [] } })
    if (path === '/api/creation/generate') {
      calls.push(route.request().postDataJSON())
      return route.fulfill({ json: { status: 'succeeded', outputs: [{ url: `https://media.example/canvas-${calls.length}.png` }], tokenId: 41, protocol: 'sync' } })
    }
    return route.fulfill({ json: {} })
  })
  await page.addInitScript(({ kind }) => {
    localStorage.setItem('octopus:user-17:native-media-settings', JSON.stringify({ autoDownload: false, autoSaveGallery: true }))
    localStorage.setItem('octopus:user-17:native-chat', JSON.stringify({ version: 1, state: {
      _hasHydrated: true, activeId: 'canvas-a', mediaConversationsMigrated: true,
      sessions: [{ id: 'canvas-a', mediaConversationId: 'canvas-a', creationKind: kind, composerKind: kind, topic: '画布测试', model: kind === 'text' ? 'gpt-5' : kind === 'video' ? 'sora-2' : 'gpt-image-2', lastUpdate: Date.now(), settings: {}, skillIds: [], messages: [] }],
    } }))
  }, { kind })
  await page.goto(`/create/${kind}`)
  await expect(page.getByRole('combobox', { name: '模型', exact: true })).toHaveValue(kind === 'text' ? 'gpt-5' : kind === 'video' ? 'sora-2' : 'gpt-image-2')
  return { calls, image, donor, account }
}
